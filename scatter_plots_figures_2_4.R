# ============================================================
# Create function for plots
# ============================================================

plot_scatter_with_ci <- function(x, y, main_title, file_name, line_col) {
  
  # Retain finite paired observations only
  ok <- is.finite(x) & is.finite(y)
  x <- x[ok]
  y <- y[ok]
  
  if (length(x) < 3) {
    stop("At least 3 finite paired observations are required.")
  }
  
  # Simple OLS regression
  fit <- lm(y ~ x)
  
  # 200 x-values and pointwise 95% CI for the fitted mean line
  newx <- seq(min(x), max(x), length.out = 200)
  
  ci_band <- predict(
    fit,
    newdata = data.frame(x = newx),
    interval = "confidence",
    level = 0.95
  )
  
  # Create high-resolution image
  png(
    filename = file_name,
    width = 3600,
    height = 2400,
    res = 600
  )
  
  on.exit(dev.off(), add = TRUE)
  
  # Set up the plot
  plot(
    x, y,
    type = "n",
    main = main_title,
    xlab = expression(Delta ~ "z-scored reaction times"),
    ylab = expression(Delta ~ "z-scored beta estimates"),
    cex.main = 1.5,
    font.main = 1,
    cex.lab = 1.5,
    cex.axis = 1.5,
    frame.plot = FALSE,
    las = 1,
    yaxt = "n"
  )
  
  # Integer y-axis labels
  y_ticks <- seq(
    floor(min(y)),
    ceiling(max(y)),
    by = 1
  )
  
  axis(
    side = 2,
    at = y_ticks,
    labels = y_ticks,
    las = 1,
    cex.axis = 1.5
  )
  
  axis(side = 1, cex.axis = 1.5)
  
  # Pointwise 95% CI band around fitted conditional mean
  polygon(
    x = c(newx, rev(newx)),
    y = c(ci_band[, "lwr"], rev(ci_band[, "upr"])),
    col = adjustcolor(line_col, alpha.f = 0.15),
    border = NA
  )
  
  # Fitted regression line
  lines(
    x = newx,
    y = ci_band[, "fit"],
    col = line_col,
    lwd = 3
  )
  
  # Participant-level datapoints
  points(
    x, y,
    pch = 19,
    cex = 1.5
  )
}


